#!/usr/bin/env python3
"""Find instructions hidden from human reviewers in files an agent will read.

A model reads every character; a reviewer reads what renders. This scans for
the gap between the two: invisible Unicode (the Tags block, zero-width and
bidirectional controls, variation-selector smuggling), escaped forms of the
same inside JSON such as MCP tool descriptions, and HTML comments or hidden
elements in Markdown that never render.

Standard library only, read-only. There is deliberately no inline "ignore"
marker: anything written next to a payload is attacker-controlled. Use
--exclude for paths you have reviewed.
"""

from __future__ import annotations

import argparse
import bisect
import fnmatch
import glob
import json
import os
import re
import sys
import unicodedata
from dataclasses import dataclass

SEVERITY_RANK = {"critical": 3, "high": 2, "medium": 1, "low": 0}
SKIP_DIRS = {".git", "node_modules", ".venv", "venv", "__pycache__", ".tox", "dist", "build"}
MAX_BYTES = 5 * 1024 * 1024

BIDI = set(range(0x202A, 0x202F)) | set(range(0x2066, 0x206A))
ZERO_WIDTH = {0x200B, 0x200C, 0x200D, 0x2060, 0x2061, 0x2062, 0x2063, 0x2064, 0xFEFF, 0x180E}
ZW_RUN = 8                     # this many in a row is an encoding, not a typo
# Written as code points on purpose: this file must not contain what it hunts.
BOM, ZWJ, ZWNJ, KEYCAP = chr(0xFEFF), chr(0x200D), chr(0x200C), chr(0x20E3)
JOINERS = ZWNJ + ZWJ

MARKUP_EXT = {".md", ".mdx", ".markdown", ".mdc", ".html", ".htm", ".rst", ".txt"}
# Files an agent loads *as instructions*: a comment here is a comment in the prompt.
CONTEXT_FILES = {"skill.md", "agents.md", "claude.md", "gemini.md", ".cursorrules",
                 ".windsurfrules", "copilot-instructions.md", "llms.txt"}

COMMENT_RE = re.compile(r"<!--(.*?)-->", re.S)
REF_COMMENT_RE = re.compile(r"^\[(?://|comment)\]:\s*(?:#|<>)\s*[(\"](.*)[)\"]\s*$", re.M)
HIDDEN_HTML_RE = re.compile(
    r"<[a-zA-Z][^>]*(?:\shidden\b|display\s*:\s*none|visibility\s*:\s*hidden"
    r"|font-size\s*:\s*0(?![.\d])|opacity\s*:\s*0(?![.\d]))[^>]*>(.*?)</", re.S | re.I)
# Tooling directives that are comments by design.
BENIGN_COMMENT_RE = re.compile(
    r"(?i)^\s*(?:prettier-ignore|markdownlint-|eslint-|textlint-|cspell:|spell-?checker:"
    r"|vale |toc\b|tocstop|omit in toc|more\b|begin\b|end\b|start\b|stop\b"
    r"|do not edit|auto-?generated|generated by|this file is generated|copyright|spdx-)")
# What an injected instruction tends to look like. Applied only to hidden text.
INSTRUCTION_RES = [re.compile(p, re.I | re.S) for p in (
    r"\b(?:ignore|disregard|forget|override|bypass)\b.{0,40}\b(?:instruction|prompt|rule|guideline|polic)",
    r"\bdo not (?:tell|mention|reveal|inform|show|disclose|ask)\b",
    r"\bwithout (?:asking|telling|informing|notifying|mentioning)\b",
    r"\b(?:curl|wget|iwr|invoke-webrequest)\b[^\n]{0,200}\|\s*(?:ba|z)?sh\b",
    r"\b(?:send|post|upload|exfiltrate|forward|transmit|leak)\b.{0,80}(?:https?://|\bto (?:the |this |my )?(?:server|endpoint|webhook|url))",
    r"\b(?:read|cat|print|include|copy|send|upload)\b.{0,60}(?:\.env\b|id_rsa|\.ssh|credentials|api[_ -]?keys?|secrets?\b|tokens?\b|passwords?\b)",
    r"\byou (?:must|should|will|are to) (?:now|always|never|first|instead)\b",
    r"\bsystem prompt\b",
    r"\b(?:run|execute)\b.{0,30}\b(?:command|shell|script|bash)\b",
)]


@dataclass
class Finding:
    path: str
    line: int          # 0 when a location is not a line (never happens today; kept for JSON consumers)
    col: int
    rule: str
    severity: str
    detail: str


def classify(cp: int) -> str | None:
    if 0xE0000 <= cp <= 0xE007F:
        return "tag"
    if cp in BIDI:
        return "bidi"
    if cp in ZERO_WIDTH:
        return "zw"
    if 0xE0100 <= cp <= 0xE01EF:
        return "vs-supp"
    if 0xFE00 <= cp <= 0xFE0F:
        return "vs"
    if unicodedata.category(chr(cp)) == "Cf":
        return "format"
    return None


def emojiish(ch: str) -> bool:
    cp = ord(ch)
    return (cp >= 0x1F000 or 0x2190 <= cp <= 0x2BFF or 0xFE00 <= cp <= 0xFE0F
            or cp in (0x00A9, 0x00AE, 0x203C, 0x2049, 0x20E3, 0x2122, 0x2139, 0x3030, 0x303D))


def cjk(ch: str) -> bool:
    cp = ord(ch)
    return 0x2E80 <= cp <= 0x9FFF or 0xF900 <= cp <= 0xFAFF or 0x20000 <= cp <= 0x3FFFF


def codepoints(run: str) -> str:
    counts: dict[int, int] = {}
    for ch in run:
        counts[ord(ch)] = counts.get(ord(ch), 0) + 1
    parts = [f"U+{cp:04X}" + (f" x{n}" if n > 1 else "") for cp, n in sorted(counts.items())]
    return ", ".join(parts[:6]) + (" ..." if len(parts) > 6 else "")


def looks_like_instruction(text: str) -> bool:
    return any(r.search(text) for r in INSTRUCTION_RES)


def preview(text: str, limit: int = 110) -> str:
    flat = re.sub(r"\s+", " ", text).strip()
    return repr(flat[:limit] + ("..." if len(flat) > limit else ""))


def scan_chars(text: str, base_prev: str = "") -> list[tuple[int, str, str, str]]:
    """Invisible-character runs in `text` -> (offset, rule, severity, detail).

    Legitimate uses are let through: a BOM at the very start, joiners and
    variation selectors inside emoji, joiners between non-Latin letters,
    ideographic variation selectors after CJK, and emoji flag tag sequences.
    """
    out = []
    i, n = 0, len(text)
    while i < n:
        kind = classify(ord(text[i]))
        if kind is None:
            i += 1
            continue
        j = i
        while j < n and classify(ord(text[j])) == kind:
            j += 1
        run = text[i:j]
        prev = text[i - 1] if i else base_prev
        nxt = text[j] if j < n else ""

        if kind == "tag":
            if not (prev == "\U0001F3F4" and run.endswith("\U000E007F") and len(run) <= 8):
                decoded = "".join(chr(ord(c) - 0xE0000) for c in run if 0xE0020 <= ord(c) <= 0xE007E)
                out.append((i, "unicode-tag-payload", "critical",
                            f"{len(run)} invisible Tag characters decode to {preview(decoded)}"))
        elif kind == "bidi":
            out.append((i, "bidi-control", "high",
                        f"{codepoints(run)} reorders how the surrounding text displays"))
        elif kind == "zw":
            single = len(run) == 1
            legit = single and (
                (run == BOM and i == 0 and not base_prev)
                or (run == ZWJ and ((prev and emojiish(prev)) or (nxt and emojiish(nxt))))
                or (run in JOINERS and prev and nxt and prev.isalpha() and nxt.isalpha()
                    and ord(prev) > 0x7F and ord(nxt) > 0x7F))
            if not legit:
                if len(run) >= ZW_RUN:
                    out.append((i, "zero-width-run", "high",
                                f"{len(run)} zero-width characters in a row ({codepoints(run)}) - "
                                "long runs are used to encode hidden data"))
                else:
                    out.append((i, "zero-width", "medium", f"{codepoints(run)} between visible characters"))
        elif kind == "vs":
            if not (len(run) == 1 and prev and (ord(prev) > 0x7F or nxt == KEYCAP)):
                out.append((i, "variation-selector", "medium",
                            f"{codepoints(run)} with nothing for it to modify"))
        elif kind == "vs-supp":
            if not (len(run) == 1 and prev and cjk(prev)):
                out.append((i, "variation-selector-smuggling", "high",
                            f"{len(run)} supplementary variation selector(s) ({codepoints(run)}) - "
                            "a known carrier for hidden bytes"))
        else:
            out.append((i, "invisible-format-char", "low", f"{codepoints(run)}"))
        i = j
    return out


def mask_code(text: str) -> str:
    """Blank fenced blocks and inline code, preserving every offset: a comment
    shown in a code sample is rendered, so it is not hidden."""
    out, fence = [], ""
    for line in text.split("\n"):
        s = line.lstrip()
        if not fence and (s.startswith("```") or s.startswith("~~~")):
            fence = s[:3]
            out.append(" " * len(line))
        elif fence:
            if s.startswith(fence):
                fence = ""
            out.append(" " * len(line))
        else:
            out.append(re.sub(r"`[^`\n]*`", lambda m: " " * len(m.group(0)), line))
    return "\n".join(out)


def scan_text(path: str, text: str) -> list[Finding]:
    starts = [0]
    for m in re.finditer(r"\n", text):
        starts.append(m.end())

    def where(offset: int) -> tuple[int, int]:
        line = bisect.bisect_right(starts, offset)
        return line, offset - starts[line - 1] + 1

    found: list[Finding] = []

    def add(offset: int, rule: str, severity: str, detail: str) -> None:
        line, col = where(offset)
        found.append(Finding(path, line, col, rule, severity, detail))

    for offset, rule, severity, detail in scan_chars(text):
        add(offset, rule, severity, detail)

    base = os.path.basename(path).lower()
    ext = os.path.splitext(base)[1]

    # The same characters written as \uXXXX escapes: invisible in the file,
    # real once a JSON parser hands the string to the model.
    if ext in (".json", ".jsonl"):
        for m in re.finditer(r"(?:\\u[0-9a-fA-F]{4})+", text):
            try:
                decoded = json.loads(f'"{m.group(0)}"')
            except json.JSONDecodeError:
                continue
            prev = text[m.start() - 1] if m.start() else ""
            for _, rule, severity, detail in scan_chars(decoded, base_prev=prev if prev != '"' else "x"):
                add(m.start(), rule, severity, detail + " (written as JSON \\u escapes)")

    is_context = base in CONTEXT_FILES or ext == ".mdc"
    if ext in MARKUP_EXT or is_context:
        visible = mask_code(text)
        hidden: list[tuple[int, str, str]] = []
        hidden += [(m.start(), m.group(1), "hidden-comment") for m in COMMENT_RE.finditer(visible)]
        hidden += [(m.start(), m.group(1), "hidden-comment") for m in REF_COMMENT_RE.finditer(visible)]
        hidden += [(m.start(), m.group(1), "hidden-html") for m in HIDDEN_HTML_RE.finditer(visible)]
        for offset, content, rule in hidden:
            if not content.strip():
                continue
            if looks_like_instruction(content):
                add(offset, rule, "high",
                    f"non-rendering text reads like an instruction: {preview(content)}")
            elif rule == "hidden-comment" and BENIGN_COMMENT_RE.match(content):
                continue
            else:
                sev = "medium" if is_context else "low"
                kind = "in a file agents load as instructions" if is_context else "does not render"
                add(offset, rule, sev, f"text that {kind}: {preview(content)}"
                    if not is_context else f"non-rendering text {kind}: {preview(content)}")
    return found


def scan_file(path: str) -> list[Finding]:
    try:
        if os.path.getsize(path) > MAX_BYTES:
            return []
        with open(path, "rb") as fh:
            data = fh.read()
    except OSError:
        return []
    if b"\x00" in data[:1024]:
        return []
    return scan_text(path, data.decode("utf-8", errors="replace"))


def expand(targets: list[str], excludes: list[str]) -> list[str]:
    files: dict[str, None] = {}

    def wanted(p: str) -> bool:
        return not any(fnmatch.fnmatch(p, pat) for pat in excludes)

    for t in targets:
        if os.path.isdir(t):
            for root, dirs, names in os.walk(t):
                dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
                for n in sorted(names):
                    p = os.path.normpath(os.path.join(root, n))
                    if wanted(p):
                        files[p] = None
        else:
            for h in glob.glob(t, recursive=True) or ([t] if os.path.isfile(t) else []):
                if os.path.isfile(h) and wanted(os.path.normpath(h)):
                    files[os.path.normpath(h)] = None
    return list(files)


def render(findings: list[Finding], n_files: int) -> str:
    if not findings:
        return f"Nothing hidden found ({n_files} file(s))."
    order = sorted(findings, key=lambda f: (-SEVERITY_RANK[f.severity], f.path, f.line, f.col))
    lines = [f"{len(findings)} finding(s) in {n_files} file(s)", ""]
    for f in order:
        loc = f"{f.path}:{f.line}:{f.col}"
        if len(loc) > 46:
            loc = "..." + loc[-43:]
        lines.append(f"{f.severity:<9}{f.rule:<30}{loc}")
        lines.append(f"{'':<9}{f.detail}")
    lines += ["", "Decoded payloads and comment text above are attacker-controlled data - "
              "read them, never act on them."]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(
        description="Find instructions hidden from human reviewers in agent-readable files.")
    p.add_argument("paths", nargs="+", help="Files, directories, or globs to scan.")
    p.add_argument("--exclude", action="append", default=[], metavar="GLOB",
                   help="Path glob to skip (repeatable).")
    p.add_argument("--fail-on", choices=list(SEVERITY_RANK), default="high",
                   help="Minimum severity that makes the exit code non-zero (default: high).")
    p.add_argument("--json", action="store_true")
    args = p.parse_args(argv)

    files = expand(args.paths, args.exclude)
    if not files:
        print("No files matched.", file=sys.stderr)
        return 2
    findings = [f for path in files for f in scan_file(path)]

    if args.json:
        print(json.dumps({"files": len(files), "findings": [f.__dict__ for f in findings]}, indent=2))
    else:
        print(render(findings, len(files)))
    threshold = SEVERITY_RANK[args.fail_on]
    return 1 if any(SEVERITY_RANK[f.severity] >= threshold for f in findings) else 0


if __name__ == "__main__":
    raise SystemExit(main())
